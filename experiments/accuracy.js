// Parameter sweeps for the reverse stage. Writes a measured baseline table to
// experiments/logs/. Not loaded by index.html.
//
//   node experiments/accuracy.js
'use strict';

const fs = require('fs');
const path = require('path');
const SIRDS = require('../sirds.js');

const W = 640;
const H = 400;
const LOG_DIR = path.join(__dirname, 'logs');
const LOG_FILE = path.join(LOG_DIR, 'accuracy-baseline.md');

function metrics(rec, gt, w, h, p) {
	let n = 0, exact = 0, within1 = 0, conf = 0, confExact = 0, confWithin1 = 0, zMae = 0;
	for (let y = p.winY; y < h - p.winY; y++) {
		for (let x = 0; x < w; x++) {
			const i = y * w + x;
			const sg = gt[i];
			const l = x - Math.ceil(sg / 2);
			if (l - p.winX < 0 || l + sg + p.winX >= w) continue;
			n++;
			const sr = rec.s[i];
			if (sr === sg) exact++;
			if (sr !== 0 && Math.abs(sr - sg) <= 1) within1++;
			if (rec.conf[i] >= 1 - p.confRel) {
				conf++;
				if (sr === sg) confExact++;
				if (sr !== 0 && Math.abs(sr - sg) <= 1) confWithin1++;
			}
			zMae += Math.abs(rec.z[i] - SIRDS.zFromS(sg, p));
		}
	}
	const pc = (a) => (100 * a / n).toFixed(1);
	return {
		n, exact: pc(exact), within1: pc(within1), conf: pc(conf),
		confExact: conf === 0 ? 'n/a' : (100 * confExact / conf).toFixed(1),
		confWithin1: conf === 0 ? 'n/a' : (100 * confWithin1 / conf).toFixed(1),
		zMae: (zMae / n).toFixed(4)
	};
}

function run(kind, over) {
	const p = SIRDS.defaultParams(over);
	const depth = SIRDS.depthPreset(kind, W, H, new Uint8Array(W * H));
	const rgba = new Uint8ClampedArray(W * H * 4);
	const scratch = SIRDS.createScratch(W);
	const gen0 = performance.now();
	SIRDS.generateSirds(depth, W, H, p, rgba, scratch);
	const tGen = performance.now() - gen0;
	const rev = SIRDS.createReverseOut(W, H, p);
	const rev0 = performance.now();
	SIRDS.reverseSirds(rgba, W, H, p, rev, scratch);
	const tRev = performance.now() - rev0;
	const gt = new Int16Array(W * H);
	for (let i = 0; i < gt.length; i++) gt[i] = SIRDS.sFromZ(depth[i] / 255, p);
	return { p, m: metrics(rev, gt, W, H, p), tGen, tRev };
}

const sweeps = [
	{ title: 'preset, default parameters', rows: ['flat', 'shapes', 'torus', 'ramp'].map((k) => ({ label: k, kind: k, over: {} })) },
	{
		title: 'match window (shapes)',
		rows: [1, 2, 3, 4, 6, 8, 12].map((wx) => ({ label: `winX=${wx}, winY=2`, kind: 'shapes', over: { winX: wx } }))
	},
	{
		title: 'match window (torus)',
		rows: [1, 2, 3, 4, 6, 8, 12].map((wx) => ({ label: `winX=${wx}, winY=2`, kind: 'torus', over: { winX: wx } }))
	},
	{
		title: 'noise grain (shapes)',
		rows: [1, 2, 3, 4, 6, 8, 12, 16].map((ns) => ({ label: `noiseScale=${ns}`, kind: 'shapes', over: { noiseScale: ns } }))
	},
	{
		title: 'period and depth strength (torus)',
		rows: [60, 100, 160, 240].flatMap((P) => [10, 20, 40, 80].map((ds) => ({ label: `P=${P}, depthScale=${ds}`, kind: 'torus', over: { P: P, depthScale: ds } })))
	}
];

const lines = [];
lines.push('# accuracy baseline');
lines.push('');
lines.push(`generated by \`node experiments/accuracy.js\` on ${new Date().toISOString().slice(0, 10)}, node ${process.version}, ${W}x${H}.`);
lines.push('');
lines.push('Metrics are over pixels whose ground-truth pair fits the window: exact / within-1 share of `s`, the confident share (residual below the cut, which means a pixel-exact match at the default cut), the within-1 share among those, and the z MAE against the quantized ground truth.');
lines.push('');

for (const sweep of sweeps) {
	lines.push(`## ${sweep.title}`);
	lines.push('');
	lines.push('| case | evaluable | exact % | within-1 % | confident % | conf exact % | conf within-1 % | z MAE | reverse ms |');
	lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
	for (const row of sweep.rows) {
		const r = run(row.kind, row.over);
		lines.push(`| ${row.label} | ${r.m.n} | ${r.m.exact} | ${r.m.within1} | ${r.m.conf} | ${r.m.confExact} | ${r.m.confWithin1} | ${r.m.zMae} | ${r.tRev.toFixed(0)} |`);
	}
	lines.push('');
}

fs.mkdirSync(LOG_DIR, { recursive: true });
fs.writeFileSync(LOG_FILE, lines.join('\n'));
process.stdout.write(lines.join('\n'));
process.stdout.write(`\nwritten: ${path.relative(process.cwd(), LOG_FILE)}\n`);
